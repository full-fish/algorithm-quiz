# 재귀 써야한다 이전값 필요하니까
def solution(n):
    dp = [1] + [0] * n

    for i in range(1, n + 1):
        for j in range(i):
            dp[i] += dp[j] * dp[i - 1 - j]
    return dp[n]


print(solution(3))
